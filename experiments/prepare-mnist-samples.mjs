#!/usr/bin/env node

import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { gunzipSync } from 'node:zlib';

const SAMPLE_COUNT = 50;
const IMAGE_URL =
  'https://storage.googleapis.com/cvdf-datasets/mnist/train-images-idx3-ubyte.gz';
const LABEL_URL =
  'https://storage.googleapis.com/cvdf-datasets/mnist/train-labels-idx1-ubyte.gz';
const OUTPUT_PATH = resolve('examples/universal-app/src/mnistSamples.js');

async function download(url) {
  console.log(`Downloading ${url}`);
  const response = await fetch(url);

  if (!response.ok) {
    throw new Error(`Failed to download ${url}: ${response.status}`);
  }

  return Buffer.from(await response.arrayBuffer());
}

function parseImages(buffer) {
  const images = gunzipSync(buffer);
  const magic = images.readUInt32BE(0);
  const count = images.readUInt32BE(4);
  const rows = images.readUInt32BE(8);
  const columns = images.readUInt32BE(12);

  if (magic !== 2051) {
    throw new Error(`Unexpected image IDX magic number: ${magic}`);
  }

  if (count < SAMPLE_COUNT) {
    throw new Error(`MNIST image file only has ${count} samples`);
  }

  const imageSize = rows * columns;
  const pixels = Buffer.alloc(SAMPLE_COUNT * imageSize);

  for (let index = 0; index < SAMPLE_COUNT; index += 1) {
    const sourceStart = 16 + index * imageSize;
    images.copy(
      pixels,
      index * imageSize,
      sourceStart,
      sourceStart + imageSize
    );
  }

  return { rows, columns, pixels };
}

function parseLabels(buffer) {
  const labels = gunzipSync(buffer);
  const magic = labels.readUInt32BE(0);
  const count = labels.readUInt32BE(4);

  if (magic !== 2049) {
    throw new Error(`Unexpected label IDX magic number: ${magic}`);
  }

  if (count < SAMPLE_COUNT) {
    throw new Error(`MNIST label file only has ${count} labels`);
  }

  return [...labels.subarray(8, 8 + SAMPLE_COUNT)];
}

function wrapBase64(value) {
  const chunks = [];

  for (let index = 0; index < value.length; index += 76) {
    chunks.push(value.slice(index, index + 76));
  }

  return chunks.map((chunk) => `  '${chunk}',`).join('\n');
}

async function main() {
  const [imageArchive, labelArchive] = await Promise.all([
    download(IMAGE_URL),
    download(LABEL_URL),
  ]);
  const images = parseImages(imageArchive);
  const labels = parseLabels(labelArchive);
  const base64 = images.pixels.toString('base64');
  const source = `// Generated by experiments/prepare-mnist-samples.mjs from the MNIST training set.
// The byte payload contains the first ${SAMPLE_COUNT} ${images.columns}x${images.rows} grayscale samples.

export const MNIST_SAMPLE_WIDTH = ${images.columns};
export const MNIST_SAMPLE_HEIGHT = ${images.rows};
export const MNIST_SAMPLE_COUNT = ${SAMPLE_COUNT};
export const MNIST_SAMPLE_LABELS = ${JSON.stringify(labels)};
export const MNIST_SAMPLE_PIXELS_BASE64 = [
${wrapBase64(base64)}
].join('');
`;

  await mkdir(dirname(OUTPUT_PATH), { recursive: true });
  await writeFile(OUTPUT_PATH, source);
  console.log(`Wrote ${OUTPUT_PATH}`);
}

await main();
